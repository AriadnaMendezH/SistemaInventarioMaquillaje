    private void btnactualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnactualizarActionPerformed
        try {

            String codigo = txtcodigo.getText().trim();
            String nombre = txtnombre.getText().trim();
            String marca = txtmarca.getText().trim();
            String categoria = cbxcategoria.getSelectedItem().toString();
            String tono = txttono.getText().trim();

            double precio = Double.parseDouble(
                    txtprecio.getText().trim()
            );

            int existencia = Integer.parseInt(
                    txtexistencia.getText().trim()
            );

            if (codigo.isEmpty()) {

                JOptionPane.showMessageDialog(
                        this,
                        "Ingresa el código del producto."
                );

                return;
            }

            Producto producto = inventario.buscarProducto(codigo);

            if (producto == null) {

                JOptionPane.showMessageDialog(
                        this,
                        "No existe un producto con ese código.",
                        "Producto no encontrado",
                        JOptionPane.WARNING_MESSAGE
                );

                return;
            }

            producto.setNombre(nombre);
            producto.setMarca(marca);
            producto.setPrecio(precio);
            producto.setExistencia(existencia);

            if (producto instanceof ProductoMaquillaje) {

                ProductoMaquillaje maquillaje
                        = (ProductoMaquillaje) producto;

                maquillaje.setCategoria(categoria);
                maquillaje.setTono(tono);
            }

            actualizarTabla();
            actualizarInformacion();
            limpiarCampos();

            JOptionPane.showMessageDialog(
                    this,
                    "Producto actualizado correctamente."
            );

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Precio y existencia deben ser números válidos.",
                    "Datos incorrectos",
                    JOptionPane.ERROR_MESSAGE
            );

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Datos incorrectos",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnactualizarActionPerformed

    private void btneliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneliminarActionPerformed
        String codigo = txtcodigo.getText().trim();

        if (codigo.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Ingresa el código del producto que deseas eliminar."
            );

            return;
        }

        Producto producto = inventario.buscarProducto(codigo);

        if (producto == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "No existe un producto con ese código.",
                    "Producto no encontrado",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        int respuesta = JOptionPane.showConfirmDialog(
                this,
                "¿Deseas eliminar el producto "
                + producto.getNombre()
                + "?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION
        );

        if (respuesta == JOptionPane.YES_OPTION) {

            inventario.eliminarProducto(codigo);

            actualizarTabla();
            actualizarInformacion();
            limpiarCampos();

            JOptionPane.showMessageDialog(
                    this,
                    "Producto eliminado correctamente."
            );
        }
    }//GEN-LAST:event_btneliminarActionPerformed

