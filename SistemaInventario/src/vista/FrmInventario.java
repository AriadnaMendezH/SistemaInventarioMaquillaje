    private void btnagregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnagregarActionPerformed
        try {

            String codigo = txtcodigo.getText().trim();
            String nombre = txtnombre.getText().trim();
            String marca = txtmarca.getText().trim();
            String categoria = cbxcategoria.getSelectedItem().toString();
            String tono = txttono.getText().trim();

            double precio = Double.parseDouble(
                    txtprecio.getText().trim()
            );

            int existencia = Integer.parseInt(
                    txtexistencia.getText().trim()
            );

            ProductoMaquillaje producto = new ProductoMaquillaje(
                    codigo,
                    nombre,
                    marca,
                    precio,
                    existencia,
                    categoria,
                    tono
            );

            boolean agregado = inventario.agregarProducto(producto);

            if (agregado) {

                JOptionPane.showMessageDialog(
                        this,
                        "Producto agregado correctamente."
                );

                actualizarTabla();
                actualizarInformacion();
                limpiarCampos();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Ya existe un producto con ese código.",
                        "Código duplicado",
                        JOptionPane.WARNING_MESSAGE
                );
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Precio y existencia deben ser números válidos.",
                    "Datos incorrectos",
                    JOptionPane.ERROR_MESSAGE
            );

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Datos incorrectos",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnagregarActionPerformed

