    private void btnbusquedaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnbusquedaActionPerformed
        String codigo = txtBusqueda.getText().trim();

        if (codigo.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Ingresa el código que deseas buscar."
            );

            return;
        }

// Búsqueda mediante el método recursivo del TDA Inventario
        Producto producto
                = inventario.buscarProductoRecursivo(codigo);

        if (producto == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "No se encontró el producto.",
                    "Búsqueda recursiva",
                    JOptionPane.WARNING_MESSAGE
            );

        } else {

            txtcodigo.setText(producto.getCodigo());
            txtnombre.setText(producto.getNombre());
            txtmarca.setText(producto.getMarca());
            txtprecio.setText(String.valueOf(producto.getPrecio()));
            txtexistencia.setText(String.valueOf(producto.getExistencia()));

            if (producto instanceof ProductoMaquillaje) {

                ProductoMaquillaje maquillaje
                        = (ProductoMaquillaje) producto;

                cbxcategoria.setSelectedItem(
                        maquillaje.getCategoria()
                );

                txttono.setText(
                        maquillaje.getTono()
                );
            }

            JOptionPane.showMessageDialog(
                    this,
                    "Producto encontrado mediante búsqueda recursiva."
            );
        }
    }//GEN-LAST:event_btnbusquedaActionPerformed

    private void tblListaProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblListaProductosMouseClicked
        int filaSeleccionada = tblListaProductos.getSelectedRow();

        if (filaSeleccionada >= 0) {

            // Obtener el código de la fila seleccionada
            String codigo = tblListaProductos
                    .getValueAt(filaSeleccionada, 0)
                    .toString();

            // Buscar el producto dentro del TDA
            Producto producto = inventario.buscarProducto(codigo);

            if (producto != null) {

                txtcodigo.setText(producto.getCodigo());
                txtnombre.setText(producto.getNombre());
                txtmarca.setText(producto.getMarca());
                txtprecio.setText(
                        String.valueOf(producto.getPrecio())
                );

                txtexistencia.setText(
                        String.valueOf(producto.getExistencia())
                );

                // Datos específicos de ProductoMaquillaje
                if (producto instanceof ProductoMaquillaje) {

                    ProductoMaquillaje maquillaje
                            = (ProductoMaquillaje) producto;

                    cbxcategoria.setSelectedItem(
                            maquillaje.getCategoria()
                    );

                    txttono.setText(
                            maquillaje.getTono()
                    );
                }
            }
        }
    }//GEN-LAST:event_tblListaProductosMouseClicked

