// Actualiza la tabla con todos los productos del inventario
    private void actualizarTabla() {

        DefaultTableModel modelo
                = (DefaultTableModel) tblListaProductos.getModel();

        // Borra las filas actuales
        modelo.setRowCount(0);

        // Recorre todos los productos registrados
        for (Producto producto : inventario.getProductos()) {

            String categoria = "";
            String tono = "";

            // Verifica si es un ProductoMaquillaje
            if (producto instanceof ProductoMaquillaje) {

                ProductoMaquillaje maquillaje
                        = (ProductoMaquillaje) producto;

                categoria = maquillaje.getCategoria();
                tono = maquillaje.getTono();
            }

            // Agrega el producto a la tabla
            modelo.addRow(new Object[]{
                producto.getCodigo(),
                producto.getNombre(),
                producto.getMarca(),
                categoria,
                tono,
                producto.getPrecio(),
                producto.getExistencia(),
                producto.calcularValorEnStock()
            });
        }
    }

// Actualiza la información general del inventario
    private void actualizarInformacion() {

        // Total de productos registrados
        txtTotalProductos.setText(
                String.valueOf(
                        inventario.obtenerCantidadProductos()
                )
        );

        // Valor total del inventario
        txtValorInventario.setText(
                String.format(
                        "$ %.2f",
                        inventario.calcularValorTotal()
                )
        );

        // Productos con existencia de 5 unidades o menos
        txtBajoStock.setText(
                String.valueOf(
                        inventario.contarProductosBajoStock(5)
                )
        );

        // Producto más caro
        Producto productoMasCaro
                = inventario.obtenerProductoMasCaro();

        if (productoMasCaro == null) {

            txtProductoMasCaro.setText("-");

        } else {

            txtProductoMasCaro.setText(
                    productoMasCaro.getNombre()
                    + " - $"
                    + String.format(
                            "%.2f",
                            productoMasCaro.getPrecio()
                    )
            );
        }
    }

